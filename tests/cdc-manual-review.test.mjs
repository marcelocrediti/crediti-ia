import assert from 'node:assert/strict';
import {categoryEvidence,manualConfirmed} from '../cdc-manual-review.mjs';
import {documentFindings,evaluateCredit,cpfMatches,identityDocument} from '../cdc-policy.mjs';
const sim={cliente:'José Silva',dadosCliente:{cpf:'52998224725'},analiseCdc:{questionario:{renda:2000,residenciaTitular:'proprio'}}};
const docs={rgFrente:{nome:'IMG_9000.jpg',dataUrl:'data:image/jpeg;base64,YQ=='}};
assert.equal(await manualConfirmed(sim,docs,'rgFrente'),false);
const evidence=await categoryEvidence(sim,docs,'rgFrente');
sim.analiseCdc.conferencias={rgFrente:{...evidence,confirmado:true,por:'admin',data:1}};
assert.equal(await manualConfirmed(sim,docs,'rgFrente'),true);
assert.equal(await manualConfirmed(sim,{rgFrente:{...docs.rgFrente,nome:'qualquer-nome.jpg'}},'rgFrente'),true);
assert.equal(await manualConfirmed(sim,{rgFrente:{...docs.rgFrente,dataUrl:'data:image/jpeg;base64,Yg=='}},'rgFrente'),false);
assert.equal(await manualConfirmed(sim,{...docs,rgVerso:{dataUrl:'data:image/jpeg;base64,Yg=='}},'rgFrente'),false);
assert.equal(await manualConfirmed({...sim,cliente:'Outra Pessoa'},docs,'rgFrente'),false);
assert.equal(await manualConfirmed(sim,{},'rgFrente'),false);
for(const tipo of ['RG','CIN','CNH','identidade'])assert(identityDocument({tipo}));
assert(!identityDocument({tipo:'outro',nomeArquivo:'CNH.pdf'}));
assert(cpfMatches({cpfParcial:'529.982.247'},'52998224725'));
assert(!cpfMatches({cpfParcial:'299822472'},'52998224725'));
assert(!cpfMatches({cpf:'52998224726',cpfParcial:'529982247'},'52998224725'));
assert(!cpfMatches({cpfParcial:'52998****'},'52998224725'));
const q={renda:2000,despesas:0,outrasParcelas:0,restricao:'nao',residenciaTitular:'proprio',documentosConferidos:true};
const readDocs=['rgFrente','comprovanteResidencia','comprovanteRenda'].map(key=>({key,label:'Nome original.pdf',manual:true,d:{tipo:'outro',legibilidade:'ilegivel',cpf:null}}));
assert.deepEqual(documentFindings({q,cliente:sim.cliente,cpf:sim.dadosCliente.cpf,readDocs}).pending,[]);
assert.equal(evaluateCredit({q,valor:500,parcela:50,documents:[{manual:true,legibilidade:'ilegivel',consecutivos:9}]}).status,'Aprovada');
assert.equal(evaluateCredit({q:{...q,restricao:'sim'},valor:500,parcela:50,documents:[{manual:true}]}).status,'Recusada');
console.log('PASS: manual evidence bound to files and client, arbitrary filenames, RG/CIN/CNH aliases, nine leading CPF digits, full conflicts preserved, human review only resolves documentary findings');
